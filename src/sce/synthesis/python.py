"""Thin JSON bridges between local Python components; no dependency installation.

Source inspection and application construction never import selected source.
The separate build adapter executes trusted code during functional verification.
"""

from dataclasses import asdict, dataclass
import ast
import hashlib
import json
from pathlib import Path, PurePosixPath
import re
from typing import Any, Callable

from sce.builders.python import CREATE_NEW_APPLICATION_USING_PROJECT, SourceFile
from sce.core.models import Evidence, OperationRecord, OperationOutcome, VerificationStatus, jsonable, utc_now


CAPABILITY_ID = "application.synthesize"
_INTERFACE = re.compile(r"[A-Za-z_]\w*(?:\.[A-Za-z_]\w*)*:[A-Za-z_]\w*", re.ASCII)
_NAME = re.compile(r"[A-Za-z0-9][A-Za-z0-9_-]{0,63}", re.ASCII)


def _json(value: Any) -> str:
    return json.dumps(value, ensure_ascii=True, sort_keys=True, separators=(",", ":"), allow_nan=False)


def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _linked(path: Path) -> bool:
    return path.is_symlink() or (hasattr(path, "is_junction") and path.is_junction())


@dataclass(frozen=True)
class ComponentSpec:
    """An inspected interface, independent of any custom project manifest."""

    source: str
    interface: str
    source_files: tuple[str, ...]
    required_modules: tuple[str, ...] = ()
    resource_id: str | None = None
    resource_revision: str | None = None


@dataclass(frozen=True)
class ComponentPlan:
    spec: ComponentSpec
    files: tuple[SourceFile, ...]
    resource_id: str
    resource_revision: str
    manifest: SourceFile | None = None


@dataclass(frozen=True)
class GeneratedFile:
    path: str
    content: str


@dataclass(frozen=True)
class SynthesisPlan:
    workspace: str
    name: str
    input_json: str
    expected_output_json: str
    trusted: bool
    task_id: str | None
    components: tuple[ComponentPlan, ...] = ()
    generated_files: tuple[GeneratedFile, ...] = ()
    validation_errors: tuple[str, ...] = ()
    operation: str = CREATE_NEW_APPLICATION_USING_PROJECT

    @property
    def ready(self) -> bool:
        return not self.validation_errors and bool(self.components)


_BRIDGE = '''"""Generated by SCE: a declared JSON interface, not model-authored execution."""
import importlib
import json
import sys

CHAIN = {chain}
MAX_INPUT_CHARS = {max_input_chars}


def main():
    if len(sys.argv) == 3 and sys.argv[1] == "--input-json":
        text = sys.argv[2]
    elif len(sys.argv) == 1:
        text = sys.stdin.read(MAX_INPUT_CHARS + 1)
    else:
        raise ValueError("Usage: application.pyz [--input-json JSON]; otherwise read JSON from stdin")
    if len(text) > MAX_INPUT_CHARS:
        raise ValueError("JSON input exceeds the declared character budget")
    value = json.loads(text, parse_constant=lambda x: (_ for _ in ()).throw(ValueError("nonfinite JSON number")))
    for module, function in CHAIN:
        if not isinstance(value, dict):
            raise ValueError("Each component input must be a JSON object")
        value = getattr(importlib.import_module(module), function)(value)
        # Enforce a portable JSON boundary after every component.
        value = json.loads(json.dumps(value, allow_nan=False))
    print(json.dumps(value, ensure_ascii=True, sort_keys=True, separators=(",", ":"), allow_nan=False))
'''


class PythonSynthesisAdapter:
    def __init__(self, *, max_source_bytes: int = 10_000_000, max_files: int = 256,
                 max_components: int = 16, max_input_chars: int = 100_000):
        for value in (max_source_bytes, max_files, max_components, max_input_chars):
            if type(value) is not int or value < 1:
                raise ValueError("Synthesis limits must be positive integers")
        self.max_source_bytes = max_source_bytes
        self.max_files = max_files
        self.max_components = max_components
        self.max_input_chars = max_input_chars

    def describe(self) -> dict[str, Any]:
        return {
            "capability_id": CAPABILITY_ID,
            "operations": [CREATE_NEW_APPLICATION_USING_PROJECT],
            "input_contract": "explicit ComponentSpec values or sce.python-component.v1 manifests; trusted local source; independent JSON input/expected output",
            "output_contract": "fresh application source workspace, provenance, JSON CLI bridge, sce.zipapp.v1 build manifest",
            "expected_effects": ["copy only selected files into isolated component namespaces", "write a fixed thin bridge and provenance; do not execute components"],
            "required_tools": ["Python 3.11+"],
            "verification": "synthesis checks exact generated/copy hashes; a separate PythonBuildAdapter checks functional output",
            "limits": {"max_source_bytes": self.max_source_bytes, "max_files": self.max_files,
                       "max_components": self.max_components, "max_input_chars": self.max_input_chars},
            "limitations": [
                "Python callable components only; module:function accepts one JSON object",
                "Functions must be explicitly defined at module top level; intermediate chain results must be JSON objects",
                "Intra-component package imports must be relative; ambient dependencies are not installed or bundled",
                "Source trust is required; generated applications and dependencies are not sandboxed",
                "No model-generated source, general autonomous interface inference, installation, or installer generation",
                "One caller-supplied fixture checks one outcome, not general application correctness",
            ],
        }

    def _read_file(self, root: Path, name: str) -> tuple[SourceFile, bytes]:
        relative = PurePosixPath(name)
        if (not isinstance(name, str) or not name or "\\" in name or ":" in name
                or relative.is_absolute() or any(part in {"", ".", ".."} for part in name.split("/"))):
            raise ValueError(f"Unsafe selected source path: {name!r}")
        candidate = root
        for part in relative.parts:
            candidate = candidate / part
            if _linked(candidate):
                raise ValueError(f"Selected source contains a link: {name}")
        if not candidate.is_file() or root not in candidate.resolve().parents:
            raise ValueError(f"Selected source is not a contained file: {name}")
        if candidate.stat().st_size > self.max_source_bytes:
            raise ValueError("Source file exceeds max_source_bytes")
        with candidate.open("rb") as stream:
            data = stream.read(self.max_source_bytes + 1)
        if len(data) > self.max_source_bytes:
            raise ValueError("Source file exceeds max_source_bytes")
        return SourceFile(name, _sha(data), len(data)), data

    def _component(self, value: ComponentSpec | Path | str) -> ComponentPlan:
        manifest = None
        if isinstance(value, ComponentSpec):
            spec = value
        else:
            supplied = Path(value).absolute()
            if _linked(supplied):
                raise ValueError("Linked component roots or manifests are unsupported")
            root = supplied if supplied.is_dir() else supplied.parent
            manifest_name = "sce-component.json" if supplied.is_dir() else supplied.name
            root = root.resolve(strict=True)
            manifest, raw = self._read_file(root, manifest_name)
            document = json.loads(raw)
            if not isinstance(document, dict) or document.get("format") != "sce.python-component.v1":
                raise ValueError("Unsupported component manifest format")
            if set(document) - {"format", "name", "description", "interface", "source_files", "required_modules"}:
                raise ValueError("Unknown component manifest fields")
            spec = ComponentSpec(str(root), document.get("interface", ""), document.get("source_files", ()),
                                 document.get("required_modules", ()))
        supplied_root = Path(spec.source).absolute()
        if _linked(supplied_root):
            raise ValueError("Linked component roots are unsupported")
        root = supplied_root.resolve(strict=True)
        if not root.is_dir():
            raise ValueError("Component source must be a directory")
        if not isinstance(spec.interface, str) or not _INTERFACE.fullmatch(spec.interface):
            raise ValueError("Interface must be module:top_level_function")
        if (not isinstance(spec.source_files, (tuple, list)) or not spec.source_files
                or any(not isinstance(name, str) for name in spec.source_files)):
            raise ValueError("source_files must contain selected relative file names")
        if len(spec.source_files) > self.max_files:
            raise ValueError("Source selection exceeds max_files")
        if len({name.casefold() for name in spec.source_files}) != len(spec.source_files):
            raise ValueError("Duplicate selected source paths")
        if (not isinstance(spec.required_modules, (tuple, list))
                or any(not isinstance(name, str) or not re.fullmatch(r"[A-Za-z_]\w*", name, re.ASCII)
                       for name in spec.required_modules)):
            raise ValueError("required_modules must contain top-level module names")
        files, contents = [], {}
        selected_bytes = 0
        for name in sorted(spec.source_files):
            snapshot, data = self._read_file(root, name)
            selected_bytes += snapshot.size
            if selected_bytes > self.max_source_bytes:
                raise ValueError("Component source selection exceeds max_source_bytes")
            files.append(snapshot)
            contents[name] = data
        module, function = spec.interface.split(":")
        module_path = module.replace(".", "/") + ".py"
        if module_path not in contents:
            module_path = module.replace(".", "/") + "/__init__.py"
        if module_path not in contents:
            raise ValueError("Interface module is not among selected source_files")
        for parent in PurePosixPath(module_path).parents:
            if parent != PurePosixPath(".") and f"{parent}/__init__.py" not in contents:
                raise ValueError(f"Selected package initializer is required: {parent}/__init__.py")
        tree = ast.parse(contents[module_path], filename=module_path)
        definitions = [node for node in tree.body if isinstance(node, ast.FunctionDef) and node.name == function]
        if len(definitions) != 1:
            raise ValueError("Interface must name one explicit synchronous top-level function")
        args = definitions[0].args
        positional = args.posonlyargs + args.args
        if (not positional or len(positional) - len(args.defaults) > 1
                or any(default is None for default in args.kw_defaults)):
            raise ValueError("Interface function must accept one positional JSON object without other required arguments")
        normalized = ComponentSpec(str(root), spec.interface, tuple(sorted(spec.source_files)),
                                   tuple(sorted(set(spec.required_modules))), spec.resource_id, spec.resource_revision)
        digest = _sha(_json([asdict(item) for item in files]).encode())
        for label in (spec.resource_id, spec.resource_revision):
            if label is not None and (not isinstance(label, str) or not label.strip()):
                raise ValueError("Resource identity and revision must be nonempty strings when supplied")
        return ComponentPlan(normalized, tuple(files), spec.resource_id or f"sha256:{digest}",
                             spec.resource_revision or f"sha256:{digest}", manifest)

    def prepare(self, component_sources: list[ComponentSpec | Path | str], workspace: Path | str, *,
                name: str, input_data: dict[str, Any], expected_output: Any, trusted: bool = False,
                task_id: str | None = None, resource_ids: list[str] | None = None,
                resource_revisions: list[str] | None = None) -> SynthesisPlan:
        """Inspect files and generate an inspectable plan entirely in memory."""
        output = Path(workspace).resolve()
        errors = []
        components: list[ComponentPlan] = []
        generated: list[GeneratedFile] = []
        input_json, expected_json = "", ""
        if trusted is not True:
            errors.append("Explicit source trust authorization is required")
        if output.exists():
            errors.append("Workspace already exists; use a fresh location")
        try:
            if not isinstance(name, str) or not _NAME.fullmatch(name):
                raise ValueError("Application name must be a safe filename of 1-64 characters")
            if not isinstance(input_data, dict):
                raise ValueError("Input must be a JSON object")
            input_json, expected_json = _json(input_data), _json(expected_output)
            if max(len(input_json), len(expected_json)) > self.max_input_chars:
                raise ValueError("Input or expected output exceeds max_input_chars")
            if not isinstance(component_sources, list) or not 1 <= len(component_sources) <= self.max_components:
                raise ValueError("Select between one and max_components components")
            for values in (resource_ids, resource_revisions):
                if values is not None and len(values) != len(component_sources):
                    raise ValueError("Resource identities/revisions must match component count")
            for index, value in enumerate(component_sources):
                part = self._component(value)
                if resource_ids is not None or resource_revisions is not None:
                    spec = ComponentSpec(**{**asdict(part.spec),
                        "resource_id": resource_ids[index] if resource_ids is not None else part.spec.resource_id,
                        "resource_revision": resource_revisions[index] if resource_revisions is not None else part.spec.resource_revision})
                    part = ComponentPlan(self._component(spec).spec, part.files,
                                         spec.resource_id or part.resource_id, spec.resource_revision or part.resource_revision,
                                         part.manifest)
                root = Path(part.spec.source)
                if output == root or root in output.parents:
                    raise ValueError("Application workspace must be outside every source directory")
                components.append(part)
            snapshots = [item for part in components for item in (*part.files, *((part.manifest,) if part.manifest else ()))]
            if len(snapshots) > self.max_files or sum(item.size for item in snapshots) > self.max_source_bytes:
                raise ValueError("Combined source selection exceeds file or byte limits")
            chain = []
            generated.append(GeneratedFile("_sce_parts/__init__.py", ""))
            for index, part in enumerate(components):
                prefix = f"_sce_parts/p{index}"
                if "__init__.py" not in part.spec.source_files:
                    generated.append(GeneratedFile(f"{prefix}/__init__.py", ""))
                module, function = part.spec.interface.split(":")
                chain.append((f"_sce_parts.p{index}.{module}", function))
            generated.append(GeneratedFile("sce_bridge.py", _BRIDGE.format(chain=repr(tuple(chain)), max_input_chars=self.max_input_chars)))
            required = sorted({name for part in components for name in part.spec.required_modules})
            manifest = {"format": "sce.zipapp.v1", "name": name, "entry_point": "sce_bridge:main",
                        "required_modules": required, "verification": {"args": ["--input-json", input_json],
                        "expected_stdout": expected_json + "\n", "expected_exit": 0}}
            generated.append(GeneratedFile("sce-build.json", _json(manifest) + "\n"))
            provenance = {"operation": CREATE_NEW_APPLICATION_USING_PROJECT,
                          "components": [asdict(part) for part in components],
                          "creation_method": "fixed thin JSON bridge; selected component files copied unchanged",
                          "acceptance_source": "caller-supplied input and expected output; not inferred from selected source",
                          "functional_verification": "NOT_RUN"}
            generated.append(GeneratedFile("sce-provenance.json", _json(provenance) + "\n"))
        except (OSError, ValueError, TypeError, SyntaxError) as exc:
            errors.append(str(exc))
        return SynthesisPlan(str(output), name, input_json, expected_json, trusted, task_id,
                             tuple(components), tuple(generated), tuple(errors))

    def _validate_prepared(self, plan: SynthesisPlan) -> dict[str, bytes]:
        """Revalidate the sealed effects and capture exactly the prepared bytes."""
        values: list[ComponentSpec | Path] = []
        for part in plan.components:
            values.append(Path(part.spec.source) / part.manifest.path if part.manifest else part.spec)
        current = self.prepare(values, plan.workspace, name=plan.name, input_data=json.loads(plan.input_json),
                               expected_output=json.loads(plan.expected_output_json), trusted=plan.trusted,
                               task_id=plan.task_id, resource_ids=[p.resource_id for p in plan.components],
                               resource_revisions=[p.resource_revision for p in plan.components])
        # The implicit content identity is identical to its explicit representation.
        original = jsonable(asdict(plan))
        refreshed = jsonable(asdict(current))
        for original_part, refreshed_part in zip(original["components"], refreshed["components"]):
            refreshed_part["spec"]["resource_id"] = original_part["spec"]["resource_id"]
            refreshed_part["spec"]["resource_revision"] = original_part["spec"]["resource_revision"]
        # Provenance embeds the normalized specs, so compare its decoded content with the same identity normalization.
        for old_file, new_file in zip(original["generated_files"], refreshed["generated_files"]):
            if old_file["path"] == new_file["path"] == "sce-provenance.json":
                old_value, new_value = json.loads(old_file["content"]), json.loads(new_file["content"])
                for old_part, new_part in zip(old_value["components"], new_value["components"]):
                    new_part["spec"]["resource_id"] = old_part["spec"]["resource_id"]
                    new_part["spec"]["resource_revision"] = old_part["spec"]["resource_revision"]
                new_file["content"] = _json(new_value) + "\n"
        if original != refreshed:
            raise ValueError("Source, destination, or prepared effects changed since PREPARE; prepare again")
        payload = {}
        for index, part in enumerate(plan.components):
            for item in part.files:
                snapshot, data = self._read_file(Path(part.spec.source), item.path)
                if snapshot != item:
                    raise ValueError("Source changed while staging; prepare again")
                payload[f"_sce_parts/p{index}/{item.path}"] = data
        payload.update({item.path: item.content.encode("utf-8") for item in plan.generated_files})
        return payload

    def execute(self, plan: SynthesisPlan, *, cancelled: Callable[[], bool] | None = None) -> OperationRecord:
        record = OperationRecord(capability_id=CAPABILITY_ID, task_id=plan.task_id,
            requested={"operation": plan.operation, "trusted": plan.trusted,
                       "resource_ids": [part.resource_id for part in plan.components]},
            planned=asdict(plan), started_at=utc_now())
        if not plan.ready:
            record.outcome = OperationOutcome.FAILED
            record.evidence.extend(Evidence(source="python.synthesize.prepare", detail=error, kind="validation")
                                   for error in plan.validation_errors)
        elif cancelled and cancelled():
            record.outcome = OperationOutcome.CANCELLED
        else:
            created = False
            try:
                payload = self._validate_prepared(plan)
                if not plan.trusted:
                    raise ValueError("Explicit source trust authorization is required")
                workspace = Path(plan.workspace)
                workspace.mkdir(parents=True, exist_ok=False)
                created = True
                for name, data in payload.items():
                    if cancelled and cancelled():
                        record.outcome = OperationOutcome.CANCELLED
                        record.unknowns.append("Application construction interrupted; partial files are preserved")
                        break
                    target = workspace / name
                    target.parent.mkdir(parents=True, exist_ok=True)
                    with target.open("xb") as stream:
                        stream.write(data)
                    record.produced.append({"kind": "application_source", "path": str(target), "sha256": _sha(data), "size": len(data)})
                    record.executed.append({"stage": "synthesis", "operation": "write_selected_or_generated_file", "path": str(target)})
                else:
                    record.outcome = OperationOutcome.SUCCEEDED
                record.produced.append({"kind": "application_workspace", "path": plan.workspace,
                                        "resource_ids": [part.resource_id for part in plan.components]})
                record.evidence.append(Evidence(source="python.synthesize.execute", kind="observation",
                    detail="Created isolated application source from declared components and fixed bridge; no component code executed"))
                record.unknowns.append("Application functionality remains unverified until separate build and functional verification")
            except (OSError, ValueError, TypeError) as exc:
                record.outcome = OperationOutcome.PARTIAL if created else OperationOutcome.FAILED
                if created:
                    record.produced.append({"kind": "partial_application_workspace", "path": plan.workspace})
                    record.unknowns.append("Incomplete application files remain in the recorded workspace for inspection")
                record.evidence.append(Evidence(source="python.synthesize.execute", detail=str(exc), kind="error"))
        record.finished_at = utc_now()
        return record

    def verify(self, plan: SynthesisPlan, record: OperationRecord, **_: Any) -> OperationRecord:
        """Verify construction integrity only; do not run the application."""
        if (record.capability_id != CAPABILITY_ID or record.task_id != plan.task_id
                or jsonable(record.planned) != jsonable(asdict(plan))):
            record.verification = VerificationStatus.FAILED
            record.evidence.append(Evidence(source="python.synthesize.verify", detail="Plan or operation identity mismatch", kind="verification"))
        elif record.outcome == OperationOutcome.SUCCEEDED:
            try:
                expected = {f"_sce_parts/p{index}/{item.path}": item.sha256
                            for index, part in enumerate(plan.components) for item in part.files}
                expected.update({item.path: _sha(item.content.encode("utf-8")) for item in plan.generated_files})
                root = Path(plan.workspace)
                actual = {path.relative_to(root).as_posix() for path in root.rglob("*") if path.is_file()}
                if set(expected) != actual:
                    raise ValueError("Constructed file set differs from the prepared application")
                for name, digest in expected.items():
                    snapshot, _ = self._read_file(root, name)
                    if snapshot.sha256 != digest:
                        raise ValueError(f"Constructed file changed: {name}")
                record.verification = VerificationStatus.PASSED
                record.evidence.append(Evidence(source="python.synthesize.verify", kind="verification",
                    detail="All selected and generated file hashes match the prepared application; construction integrity only, not functionality"))
            except (OSError, ValueError) as exc:
                record.verification = VerificationStatus.FAILED
                record.evidence.append(Evidence(source="python.synthesize.verify", detail=str(exc), kind="verification"))
        else:
            record.unknowns.append("Construction integrity verification was not run because synthesis did not succeed")
        record.finished_at = utc_now()
        return record

    def report(self, record: OperationRecord) -> OperationRecord:
        return record
